def is_active_valid(expires_at, target_dir, cad_exts, ext):
    """Oracle function determining whether active project should be considered active and match."""
    # 1. Target directory check
    if not target_dir or not str(target_dir).strip():
        return False

    # 2. Expiry check
    if expires_at is not None:
        try:
            exp_val = float(expires_at)
            if math.isnan(exp_val) or exp_val < 0 or (exp_val > 0 and time.time() >= exp_val):
                return False
        except (ValueError, TypeError):
            return False

    # 3. CAD extension check
    if cad_exts is None or not isinstance(cad_exts, (list, tuple, set)):
        allowed_exts = set(CAD_EXTENSIONS)
    elif not all(isinstance(e, str) for e in cad_exts):
        allowed_exts = set(CAD_EXTENSIONS)
    else:
        allowed_exts = {e.lower() for e in cad_exts}

    return ext.lower() in allowed_exts


@pytest.mark.parametrize("expires_at", EXPIRES_AT_VALUES)
@pytest.mark.parametrize("target_dir", TARGET_DIR_VALUES)
@pytest.mark.parametrize("cad_exts", CAD_EXT_VALUES)
def test_matrix_me3210_exam_review_pdf_always_bypasses(config, expires_at, target_dir, cad_exts):
    """ME3210_Exam_Review.pdf must ALWAYS route to Documents\\School via keyword match.

    It must never route to active project or raise any exception regardless of
    active project parameters.
    """
    proj = {
        "enabled": True,
        "project_name": "Turbine Bracket",
        "target_directory": target_dir,
        "expires_at": expires_at,
        "cad_extensions": cad_exts,
    }

    res = evaluate_routing("ME3210_Exam_Review.pdf", config, active_project=proj)

    assert isinstance(res, dict)
    assert res["is_active_project"] is False
    assert res["match_type"] == "keyword"
    assert res["destination"] == "Documents\\School"
    assert res["winning_rule"] == "School Documents"


