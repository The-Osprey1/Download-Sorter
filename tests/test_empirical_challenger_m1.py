def test_adversarial_unpack_3d_archive_with_corrupt_active_project(tmp_path, config):
    """unpack_3d_archive falls back safely to Downloads/3D Models when active project has corrupt expiry or path."""
    import zipfile
    from unzip_3d import unpack_3d_archive

    zip_file = tmp_path / "multi_part.zip"
    with zipfile.ZipFile(zip_file, "w") as z:
        z.writestr("part_a.stl", b"solid part_a\nendsolid part_a\n")
        z.writestr("part_b.3mf", b"fake 3mf content")

    corrupt_proj = {
        "enabled": True,
        "target_directory": "   ",
        "expires_at": "INVALID_FLOAT",
    }
    extracted = unpack_3d_archive(zip_file, config, active_project=corrupt_proj)
    assert len(extracted) == 2
    # Verify it extracted into default folder rather than crashing or using whitespace path
    for p in extracted:
        assert p.exists()
        assert "3D Models" in str(p)

