def test_vulnerability_cad_extensions_none_raises_typeerror(base_config):
    """cad_extensions=None safely falls back to CAD_EXTENSIONS without throwing TypeError."""
    res = evaluate_routing("part.stl", base_config, active_project={"enabled": True, "target_directory": "C:\\Target", "cad_extensions": None})
    assert res["match_type"] == "active_project"
    assert res["destination"] == "C:\\Target"

def test_vulnerability_cad_extensions_non_string_raises_attribute_error(base_config):
    """cad_extensions with non-string items safely falls back to CAD_EXTENSIONS without throwing AttributeError."""
    res = evaluate_routing("part.stl", base_config, active_project={"enabled": True, "target_directory": "C:\\Target", "cad_extensions": [123, None]})
    assert res["match_type"] == "active_project"
    assert res["destination"] == "C:\\Target"

