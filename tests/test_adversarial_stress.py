# 1. Ambiguous G-Code Headers (Haas vs 3D printer mixes)
# ============================================================================

def test_ambiguous_header_haas_dominant(base_config):
    """Haas program with 3D slicer comments in header; Haas codes dominate."""
    sample = """%
O01234 (BRACKET MILLING)
; generated by BambuStudio 01.09.02
; layer_height = 0.20
G00 G90 G20 G40 G49 G80 G17
G90 G54
T1 M06
S4000 M03
G43 H01 Z0.5
M08
G01 X1.0 Y1.0 F30.
M09
M05
G00 G91 G28 Z0.
M30
%
"""
    sniff = sniff_machine_type(sample)
    assert sniff["is_haas"] is True
    assert sniff["is_3d_printer"] is False
    assert sniff["machine_type"] == "haas_cnc"

    res = evaluate_routing("bracket.nc", base_config, content_sample=sample)
    assert res["match_type"] == "gcode_sniffer"
    assert res["destination"] == "Code\\Haas"

