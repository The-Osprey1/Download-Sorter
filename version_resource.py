"""Write the Windows version resource (file properties) that PyInstaller embeds in the .exe (#9).

An .exe with no company, description or version looks anonymous to antivirus heuristics and
SmartScreen. This fills in the same details the app shows everywhere else (about.py), so the
file's Properties > Details tab names the publisher and version. build_release.py writes it
before PyInstaller runs; the spec file points each executable at it.
"""

from __future__ import annotations

from pathlib import Path


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """'2.3.0' -> (2, 3, 0, 0); anything unreadable becomes zeros for the missing parts."""
    parts = [int(p) for p in str(version).split("-")[0].split(".") if p.isdigit()][:4]
    parts += [0] * (4 - len(parts))
    return tuple(parts)  # type: ignore[return-value]


def render(version: str, author: str, year: int, app_name: str, file_name: str) -> str:
    v = version_tuple(version)
    copyright_line = f"Copyright (c) {year} {author}"
    return f"""# UTF-8
# Generated by version_resource.py from about.py; do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={v},
    prodvers={v},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        u'040904B0',
        [StringStruct(u'CompanyName', u'{author}'),
        StringStruct(u'FileDescription', u'{app_name}'),
        StringStruct(u'FileVersion', u'{version}'),
        StringStruct(u'InternalName', u'{file_name}'),
        StringStruct(u'LegalCopyright', u'{copyright_line}. Licensed under the MIT License.'),
        StringStruct(u'OriginalFilename', u'{file_name}.exe'),
        StringStruct(u'ProductName', u'{app_name}'),
        StringStruct(u'ProductVersion', u'{version}')])
      ]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


def write(path: Path | str, file_name: str = "DownloadSorter") -> Path:
    import about
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        render(about.__version__, about.AUTHOR, about.YEAR, about.APP_NAME, file_name),
        encoding="utf-8",
    )
    return target


